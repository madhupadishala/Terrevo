begin;

create table public.customer_relationships(
  id uuid primary key default extensions.gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  source_kind text not null check(source_kind in('doctor','chemist')),
  source_id uuid not null,
  target_kind text not null check(target_kind in('chemist','stockist')),
  target_id uuid not null,
  relationship text not null check(relationship in('DOCTOR_CHEMIST','CHEMIST_STOCKIST')),
  created_by uuid not null,
  created_at timestamptz not null default now(),
  unique(tenant_id,id),
  unique(tenant_id,source_kind,source_id,target_kind,target_id),
  foreign key(tenant_id,created_by) references public.tenant_memberships(tenant_id,user_id) on delete restrict,
  check(
    (source_kind='doctor' and target_kind='chemist' and relationship='DOCTOR_CHEMIST')
    or
    (source_kind='chemist' and target_kind='stockist' and relationship='CHEMIST_STOCKIST')
  )
);

create table public.customer_relationship_audit(
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  relationship_id uuid not null,
  actor_user_id uuid not null,
  action text not null check(action in('LINK','UNLINK')),
  source_kind text not null,
  source_id uuid not null,
  target_kind text not null,
  target_id uuid not null,
  occurred_at timestamptz not null default now(),
  foreign key(tenant_id,actor_user_id) references public.tenant_memberships(tenant_id,user_id) on delete restrict
);

create index customer_relationships_source_idx on public.customer_relationships(tenant_id,source_kind,source_id);
create index customer_relationships_target_idx on public.customer_relationships(tenant_id,target_kind,target_id);
create index customer_relationship_audit_tenant_idx on public.customer_relationship_audit(tenant_id,occurred_at desc);

create or replace function public.customer_kind_territory(
  p_tenant_id uuid,p_kind text,p_id uuid
)
returns uuid
language plpgsql
stable
security definer
set search_path=''
as $$
declare v_territory uuid;
begin
  if p_kind='doctor' then
    select territory_id into v_territory from public.doctors
      where tenant_id=p_tenant_id and id=p_id and status='active';
  elsif p_kind='chemist' then
    select territory_id into v_territory from public.chemists
      where tenant_id=p_tenant_id and id=p_id and status='active';
  elsif p_kind='stockist' then
    select territory_id into v_territory from public.stockists
      where tenant_id=p_tenant_id and id=p_id and status='active';
  else
    return null;
  end if;
  return v_territory;
end;
$$;

create or replace function public.can_read_customer_relationship(
  p_tenant_id uuid,p_source_kind text,p_source_id uuid,p_target_kind text,p_target_id uuid
)
returns boolean
language plpgsql
stable
security definer
set search_path=''
as $$
declare v_source_territory uuid;v_target_territory uuid;
begin
  v_source_territory:=public.customer_kind_territory(p_tenant_id,p_source_kind,p_source_id);
  v_target_territory:=public.customer_kind_territory(p_tenant_id,p_target_kind,p_target_id);
  if v_source_territory is null or v_target_territory is null then return false;end if;
  return public.has_master_access(p_tenant_id,v_source_territory)
    and public.has_master_access(p_tenant_id,v_target_territory);
end;
$$;

create or replace function public.admin_link_customer(
  p_tenant_id uuid,p_user_id uuid,p_source_kind text,p_source_id uuid,p_target_kind text,p_target_id uuid
)
returns uuid
language plpgsql
security definer
set search_path=''
as $$
declare v_relationship text;v_id uuid;v_source_territory uuid;v_target_territory uuid;
begin
  if p_source_kind='doctor' and p_target_kind='chemist' then v_relationship:='DOCTOR_CHEMIST';
  elsif p_source_kind='chemist' and p_target_kind='stockist' then v_relationship:='CHEMIST_STOCKIST';
  else raise exception 'unsupported customer relationship';end if;

  if not exists(select 1 from public.tenant_memberships m where m.tenant_id=p_tenant_id and m.user_id=p_user_id and m.status='active')
  then raise exception 'active tenant membership required';end if;

  v_source_territory:=public.customer_kind_territory(p_tenant_id,p_source_kind,p_source_id);
  v_target_territory:=public.customer_kind_territory(p_tenant_id,p_target_kind,p_target_id);
  if v_source_territory is null or v_target_territory is null then raise exception 'active customer not found';end if;

  select id into v_id from public.customer_relationships
   where tenant_id=p_tenant_id and source_kind=p_source_kind and source_id=p_source_id
     and target_kind=p_target_kind and target_id=p_target_id;
  if v_id is not null then return v_id;end if;

  insert into public.customer_relationships(
    tenant_id,source_kind,source_id,target_kind,target_id,relationship,created_by
  ) values(
    p_tenant_id,p_source_kind,p_source_id,p_target_kind,p_target_id,v_relationship,p_user_id
  ) returning id into v_id;

  insert into public.customer_relationship_audit(
    tenant_id,relationship_id,actor_user_id,action,source_kind,source_id,target_kind,target_id
  ) values(p_tenant_id,v_id,p_user_id,'LINK',p_source_kind,p_source_id,p_target_kind,p_target_id);

  return v_id;
end;
$$;

create or replace function public.admin_unlink_customer(
  p_tenant_id uuid,p_user_id uuid,p_relationship_id uuid
)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare v_row public.customer_relationships%rowtype;
begin
  select * into v_row from public.customer_relationships
   where tenant_id=p_tenant_id and id=p_relationship_id for update;
  if v_row.id is null then raise exception 'customer relationship not found';end if;
  if not exists(select 1 from public.tenant_memberships m where m.tenant_id=p_tenant_id and m.user_id=p_user_id and m.status='active')
  then raise exception 'active tenant membership required';end if;

  insert into public.customer_relationship_audit(
    tenant_id,relationship_id,actor_user_id,action,source_kind,source_id,target_kind,target_id
  ) values(p_tenant_id,v_row.id,p_user_id,'UNLINK',v_row.source_kind,v_row.source_id,v_row.target_kind,v_row.target_id);

  delete from public.customer_relationships where tenant_id=p_tenant_id and id=p_relationship_id;
end;
$$;

create or replace function public.require_rcpa_outlet_link()
returns trigger
language plpgsql
set search_path=''
as $$
begin
  if not exists(
    select 1 from public.customer_relationships r
     where r.tenant_id=new.tenant_id and r.relationship='DOCTOR_CHEMIST'
       and r.target_kind='chemist' and r.target_id=new.chemist_id
  ) then raise exception 'RCPA requires the chemist to be linked to at least one doctor';end if;
  return new;
end;
$$;

create trigger rcpa_outlet_link_guard
before insert or update of chemist_id on public.rcpa_reports
for each row execute function public.require_rcpa_outlet_link();

create or replace function public.require_pob_outlet_link()
returns trigger
language plpgsql
set search_path=''
as $$
begin
  if new.customer_type='chemist' then
    if not exists(
      select 1 from public.customer_relationships r
       where r.tenant_id=new.tenant_id and r.relationship='CHEMIST_STOCKIST'
         and r.source_kind='chemist' and r.source_id=new.chemist_id
    ) then raise exception 'POB requires the chemist to be linked to at least one stockist';end if;
  elsif new.customer_type='stockist' then
    if not exists(
      select 1 from public.customer_relationships r
       where r.tenant_id=new.tenant_id and r.relationship='CHEMIST_STOCKIST'
         and r.target_kind='stockist' and r.target_id=new.stockist_id
    ) then raise exception 'POB requires the stockist to be linked to at least one chemist';end if;
  end if;
  return new;
end;
$$;

create trigger sales_order_outlet_link_guard
before insert or update of chemist_id,stockist_id on public.sales_orders
for each row execute function public.require_pob_outlet_link();

alter table public.customer_relationships enable row level security;
alter table public.customer_relationship_audit enable row level security;
revoke all on public.customer_relationships from anon,authenticated;
revoke all on public.customer_relationship_audit from anon,authenticated;
grant select on public.customer_relationships to authenticated;

create policy customer_relationships_scoped_read
on public.customer_relationships
for select
to authenticated
using(public.can_read_customer_relationship(tenant_id,source_kind,source_id,target_kind,target_id));

revoke all on function public.customer_kind_territory(uuid,text,uuid) from public;
revoke all on function public.can_read_customer_relationship(uuid,text,uuid,text,uuid) from public;
revoke all on function public.admin_link_customer(uuid,uuid,text,uuid,text,uuid) from public;
revoke all on function public.admin_unlink_customer(uuid,uuid,uuid) from public;
grant execute on function public.can_read_customer_relationship(uuid,text,uuid,text,uuid) to authenticated;
grant execute on function public.admin_link_customer(uuid,uuid,text,uuid,text,uuid) to service_role;
grant execute on function public.admin_unlink_customer(uuid,uuid,uuid) to service_role;

commit;
